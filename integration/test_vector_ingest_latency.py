"""
Worst-case ingestion latency for HASH vectors on a FLAT index.

Goal: expose main-thread stalls (e.g. non-incremental rehashing of
VectorRegistry::tracked_vectors_ or IndexSchema::db_key_info_) while ingesting
a very large number of unique vectors with enough parallel clients to saturate
the main thread.

Load is generated by many processes (each with a few raw-socket clients) to
avoid GIL-induced latency. A separate PING probe process measures pure
main-thread stalls, independent of writer-thread backlog (HSET from a real
client is blocked until a writer thread indexes it).

These tests are long-running and memory hungry, so they only run when
VECTOR_INGEST_LATENCY=1. Knobs:
  VECTOR_INGEST_LATENCY_NUM_KEYS          default 100_000_000
  VECTOR_INGEST_LATENCY_CLIENTS           default 32
  VECTOR_INGEST_LATENCY_THREADS_PER_PROC  default 2
  VECTOR_INGEST_LATENCY_SWEEP             default 32,64,128,256,384,512
  VECTOR_INGEST_LATENCY_SWEEP_SECONDS     default 15
  VECTOR_INGEST_LATENCY_MODULE_ARGS       extra search module args, e.g.
                                          "--enable-vector-sharing no"
"""

import heapq
import json
import math
import multiprocessing
import os
import socket
import struct
import threading
import time

import pytest
from valkey_search_test_case import ValkeySearchTestCaseBase
from valkeytestframework.conftest import resource_port_tracker
from ft_info_parser import FTInfoParser

ENABLED = os.getenv("VECTOR_INGEST_LATENCY") == "1"
NUM_KEYS = int(os.getenv("VECTOR_INGEST_LATENCY_NUM_KEYS", "100000000"))
CLIENTS = int(os.getenv("VECTOR_INGEST_LATENCY_CLIENTS", "32"))
THREADS_PER_PROC = int(os.getenv("VECTOR_INGEST_LATENCY_THREADS_PER_PROC", "2"))
SWEEP = [
    int(c)
    for c in os.getenv(
        "VECTOR_INGEST_LATENCY_SWEEP", "32,64,128,256,384,512"
    ).split(",")
]
SWEEP_SECONDS = int(os.getenv("VECTOR_INGEST_LATENCY_SWEEP_SECONDS", "15"))
MODULE_ARGS = os.getenv("VECTOR_INGEST_LATENCY_MODULE_ARGS", "")

INDEX = "idx"
PREFIX = "k:"
DIM = 4
TOP_K = 20
# Histogram buckets: 8 per power of two of microseconds.
BUCKETS_PER_OCTAVE = 8
NUM_BUCKETS = 40 * BUCKETS_PER_OCTAVE


def vector_bytes(key_id: int) -> bytes:
    # Every component is an integer < 2^24, so float32 holds it exactly and
    # (low24, high bits) is unique per key id. Finite and non-zero magnitude.
    return struct.pack(
        "<4f", key_id & 0xFFFFFF, key_id >> 24, 1.0 + (key_id % 7), 1.0
    )


def hset_command(key_id: int) -> bytes:
    key = f"{PREFIX}{key_id}".encode()
    return (
        b"*4\r\n$4\r\nHSET\r\n$%d\r\n%s\r\n$1\r\nv\r\n$16\r\n%s\r\n"
        % (len(key), key, vector_bytes(key_id))
    )


def bucket_of(lat_ns: int) -> int:
    us = lat_ns / 1000.0
    if us <= 1.0:
        return 0
    return min(int(math.log2(us) * BUCKETS_PER_OCTAVE), NUM_BUCKETS - 1)


def bucket_upper_us(b: int) -> float:
    return 2 ** ((b + 1) / BUCKETS_PER_OCTAVE)


class LatencyStats:
    """Count, histogram and top-K (latency_ns, key_id, wall_time) samples."""

    def __init__(self):
        self.count = 0
        self.hist = [0] * NUM_BUCKETS
        self.top = []

    def add(self, lat_ns, key_id, wall):
        self.count += 1
        self.hist[bucket_of(lat_ns)] += 1
        if len(self.top) < TOP_K:
            heapq.heappush(self.top, (lat_ns, key_id, wall))
        elif lat_ns > self.top[0][0]:
            heapq.heapreplace(self.top, (lat_ns, key_id, wall))

    def merge(self, other: dict):
        self.count += other["count"]
        self.hist = [a + b for a, b in zip(self.hist, other["hist"])]
        for t in other["top"]:
            if len(self.top) < TOP_K:
                heapq.heappush(self.top, tuple(t))
            elif t[0] > self.top[0][0]:
                heapq.heapreplace(self.top, tuple(t))

    def to_dict(self):
        return {"count": self.count, "hist": self.hist, "top": self.top}

    def percentile_us(self, p: float) -> float:
        target = self.count * p / 100.0
        seen = 0
        for b, n in enumerate(self.hist):
            seen += n
            if seen >= target and n:
                return bucket_upper_us(b)
        return 0.0

    def max_us(self) -> float:
        return max(self.top)[0] / 1000.0 if self.top else 0.0


def read_reply(sock: socket.socket) -> bytes:
    data = sock.recv(256)
    while not data.endswith(b"\r\n"):
        more = sock.recv(256)
        if not more:
            raise ConnectionError("server closed connection")
        data += more
    return data


def connect(port: int) -> socket.socket:
    sock = socket.create_connection(("127.0.0.1", port))
    sock.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
    return sock


def client_loop(port, ranges, duration, go, stats, errors):
    """One client: HSET each key in its id ranges until done or duration."""
    sock = connect(port)
    go.wait()
    deadline = time.time() + duration if duration else None
    perf = time.perf_counter_ns
    for lo, hi in ranges:
        for key_id in range(lo, hi):
            cmd = hset_command(key_id)
            t0 = perf()
            sock.sendall(cmd)
            reply = read_reply(sock)
            lat = perf() - t0
            if reply[0:1] != b":":
                errors.append(reply.decode(errors="replace"))
                return
            stats.add(lat, key_id, time.time())
            if deadline and (key_id & 0xFF) == 0 and time.time() > deadline:
                sock.close()
                return
    sock.close()


def load_process(port, client_ranges, duration, go, out):
    """Runs len(client_ranges) clients as threads; reports merged stats."""
    stats = LatencyStats()
    errors = []
    lock = threading.Lock()

    def run(ranges):
        local = LatencyStats()
        try:
            client_loop(port, ranges, duration, go, local, errors)
        except Exception as e:  # report, don't hang the parent
            errors.append(repr(e))
        with lock:
            stats.merge(local.to_dict())

    threads = [
        threading.Thread(target=run, args=(r,)) for r in client_ranges
    ]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    out.put({"stats": stats.to_dict(), "errors": errors})


def probe_process(port, go, stop, out):
    """PING every ~1ms; measures main-thread responsiveness."""
    stats = LatencyStats()
    sock = connect(port)
    go.wait()
    perf = time.perf_counter_ns
    seq = 0
    while not stop.is_set():
        t0 = perf()
        sock.sendall(b"*1\r\n$4\r\nPING\r\n")
        read_reply(sock)
        stats.add(perf() - t0, seq, time.time())
        seq += 1
        time.sleep(0.001)
    sock.close()
    out.put(stats.to_dict())


def main_thread_cpu_seconds(pid: int) -> float:
    # The valkey main thread's tid == pid. utime/stime are fields 14/15.
    with open(f"/proc/{pid}/task/{pid}/stat") as f:
        fields = f.read().rsplit(")", 1)[1].split()
    return (int(fields[11]) + int(fields[12])) / os.sysconf("SC_CLK_TCK")


@pytest.mark.skipif(not ENABLED, reason="set VECTOR_INGEST_LATENCY=1 to run")
class TestVectorIngestLatency(ValkeySearchTestCaseBase):

    def get_config_file_lines(self, testdir, port):
        lines = super().get_config_file_lines(testdir, port)
        module = f"loadmodule {os.getenv('MODULE_PATH')}"
        return [f"{l} {MODULE_ARGS}" if l == module else l for l in lines]

    def create_index(self):
        self.client.execute_command(
            "FT.CREATE", INDEX, "ON", "HASH", "PREFIX", "1", PREFIX,
            "SCHEMA", "v", "VECTOR", "FLAT", "6",
            "TYPE", "FLOAT32", "DIM", str(DIM), "DISTANCE_METRIC", "L2",
        )

    def server_pid(self) -> int:
        return int(self.client.info("server")["process_id"])

    def commands_processed(self) -> int:
        return int(self.client.info("stats")["total_commands_processed"])

    def run_load(self, num_clients, key_base, keys_per_client, duration=None,
                 monitor=None):
        """Starts load + probe processes. Returns (hset_stats, probe_stats, seconds)."""
        ctx = multiprocessing.get_context("spawn")
        go, stop, out, probe_out = ctx.Event(), ctx.Event(), ctx.Queue(), ctx.Queue()
        port = self.server.port
        ranges = [
            [(key_base + c * keys_per_client,
              key_base + (c + 1) * keys_per_client)]
            for c in range(num_clients)
        ]
        procs = [
            ctx.Process(target=load_process,
                        args=(port, ranges[i:i + THREADS_PER_PROC], duration,
                              go, out))
            for i in range(0, num_clients, THREADS_PER_PROC)
        ]
        probe = ctx.Process(target=probe_process,
                            args=(port, go, stop, probe_out))
        for p in procs + [probe]:
            p.start()
        # Let every client connect before starting.
        while int(self.client.info("clients")["connected_clients"]) < num_clients + 2:
            time.sleep(0.1)
        start = time.time()
        go.set()
        hset = LatencyStats()
        errors = []
        for _ in procs:
            while True:
                if monitor:
                    monitor()
                try:
                    r = out.get(timeout=1)
                    break
                except Exception:
                    continue
            hset.merge(r["stats"])
            errors += r["errors"]
        elapsed = time.time() - start
        stop.set()
        probe_stats = LatencyStats()
        probe_stats.merge(probe_out.get())
        for p in procs + [probe]:
            p.join()
        assert not errors, errors[:10]
        return hset, probe_stats, elapsed

    def test_main_thread_saturation(self):
        """Sweep client counts; report throughput and main-thread CPU."""
        self.create_index()
        pid = self.server_pid()
        results = []
        key_base = 0
        keys_per_client = 10_000_000
        warmup = 3
        for clients in SWEEP:
            samples = {}

            def sample(start_time=[None]):
                now = time.time()
                if start_time[0] is None:
                    start_time[0] = now
                t = now - start_time[0]
                if "begin" not in samples and t >= warmup:
                    samples["begin"] = (now, self.commands_processed(),
                                        main_thread_cpu_seconds(pid))
                if "end" not in samples and t >= SWEEP_SECONDS - 1:
                    samples["end"] = (now, self.commands_processed(),
                                      main_thread_cpu_seconds(pid))

            self.run_load(clients, key_base, keys_per_client,
                          duration=SWEEP_SECONDS, monitor=sample)
            key_base += clients * keys_per_client
            (t0, c0, cpu0), (t1, c1, cpu1) = samples["begin"], samples["end"]
            ops = (c1 - c0) / (t1 - t0)
            cpu = 100.0 * (cpu1 - cpu0) / (t1 - t0)
            results.append({"clients": clients, "ops_per_sec": ops,
                            "main_thread_cpu_pct": cpu})
            print(f"clients={clients:4d} ops/s={ops:10.0f} "
                  f"main-thread-cpu={cpu:5.1f}%", flush=True)

        # Saturated = adding clients no longer raises throughput (<5%) while
        # the main thread is busy. /proc CPU tops out below 100% because the
        # main thread also waits for a core behind writer threads and clients.
        saturated = None
        for cur, nxt in zip(results, results[1:]):
            if (cur["main_thread_cpu_pct"] >= 85.0
                    and nxt["ops_per_sec"] < cur["ops_per_sec"] * 1.05):
                saturated = cur
                break
        print(f"saturation point: {saturated}", flush=True)
        self.write_results("saturation", {"sweep": results,
                                          "saturated": saturated})
        assert saturated is not None, f"main thread never saturated: {results}"

    def test_flat_ingest_worst_latency(self):
        """Ingest NUM_KEYS unique vectors; report worst-case latency."""
        self.create_index()
        self.client.execute_command("CONFIG", "SET",
                                    "latency-monitor-threshold", "1")
        pid = self.server_pid()
        assert NUM_KEYS % CLIENTS == 0, "NUM_KEYS must divide by CLIENTS"
        timeline = []
        last = [0.0]

        def monitor():
            now = time.time()
            if now - last[0] < 1.0:
                return
            last[0] = now
            timeline.append((now, self.client.dbsize(),
                             self.commands_processed(),
                             main_thread_cpu_seconds(pid)))
            if len(timeline) % 30 == 0:
                print(f"t={now - timeline[0][0]:6.0f}s keys={timeline[-1][1]}",
                      flush=True)

        hset, probe, elapsed = self.run_load(
            CLIENTS, 0, NUM_KEYS // CLIENTS, monitor=monitor)

        info = FTInfoParser(self.client.execute_command("FT.INFO", INDEX))
        assert info.num_docs == NUM_KEYS
        assert hset.count == NUM_KEYS
        sample_ids = range(0, NUM_KEYS, max(1, NUM_KEYS // 10_000))
        vectors = [self.client.hget(f"{PREFIX}{i}", "v") for i in sample_ids]
        assert all(v == vector_bytes(i) for i, v in zip(sample_ids, vectors))
        assert len(set(vectors)) == len(vectors)

        def keys_at(wall):
            # DBSIZE from the nearest monitor sample at or before `wall`.
            best = timeline[0][1] if timeline else 0
            for t, keys, _, _ in timeline:
                if t > wall:
                    break
                best = keys
            return best

        latency_latest = self.client.execute_command("LATENCY", "LATEST")
        report = {
            "num_keys": NUM_KEYS,
            "clients": CLIENTS,
            "seconds": elapsed,
            "ops_per_sec": NUM_KEYS / elapsed,
            "hset_us": {p: hset.percentile_us(p) for p in (50, 99, 99.9, 99.99)},
            "hset_max_us": hset.max_us(),
            "hset_top": [
                {"us": l / 1000.0, "key_id": k, "keys_at": keys_at(w)}
                for l, k, w in sorted(hset.top, reverse=True)
            ],
            "ping_us": {p: probe.percentile_us(p) for p in (50, 99, 99.9)},
            "ping_max_us": probe.max_us(),
            "ping_top": [
                {"us": l / 1000.0, "keys_at": keys_at(w)}
                for l, _, w in sorted(probe.top, reverse=True)
            ],
            "latency_latest": [
                [x.decode() if isinstance(x, bytes) else x for x in row]
                for row in latency_latest
            ],
            "timeline": [
                {"t": t - timeline[0][0], "keys": k, "cmds": c, "cpu": cpu}
                for t, k, c, cpu in timeline
            ],
        }
        summary = {k: v for k, v in report.items() if k != "timeline"}
        print(json.dumps(summary, indent=2), flush=True)
        self.write_results("ingest", report)

    def write_results(self, name, data):
        path = os.path.join(os.environ.get("LOGS_DIR", "."), self.test_name,
                            f"vector_ingest_latency_{name}.json")
        with open(path, "w") as f:
            json.dump(data, f, indent=2)
        print(f"results written to {path}", flush=True)
